    private void buttonRegistrarOfertaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonRegistrarOfertaActionPerformed
        Oferta oferta = new Oferta();
        DefaultComboBoxModel modelPostulante = (DefaultComboBoxModel) comboPostulante.getModel();
        DefaultComboBoxModel modelProducto = (DefaultComboBoxModel) comboProducto.getModel();
        
        if(modelPostulante.getSelectedItem() == null || modelProducto.getSelectedItem() == null){
            System.out.println("Debe seleccionar un item y un postulanate");
            return;
        }
        
        try {
            String texto = textMonto.getText().trim().replace(",", ".");
            BigDecimal monto = new BigDecimal(texto);
            oferta.setMonto(monto);
        } catch (NumberFormatException ex) {
            System.out.println("Error: el monto no es válido");
            return;
        }
      
        oferta.setDniPostulante((Postulante) modelPostulante.getSelectedItem());
        oferta.setIdProducto((Producto) modelProducto.getSelectedItem());
        oferta.setFechaCreacion(LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss")));
        
        if(oferta.getIdProducto().getPrecioBase().doubleValue() > oferta.getMonto().doubleValue()){
            System.out.println("El monto a ofertar debe ser mayor al precio base");
            return;
        }
        
        oferta.setEstado(oferta.validaMontoSincronizado(oferta.getMonto(), oferta.getIdProducto().getId()));
        
        oferta.registrarOfertaSincronizada(oferta);
        
        modelPostulante.setSelectedItem(null);
        modelProducto.setSelectedItem(null);
        textMonto.setText("");
        
    }//GEN-LAST:event_buttonRegistrarOfertaActionPerformed

