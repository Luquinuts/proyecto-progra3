    @Override
    public void onShow() {
        DefaultComboBoxModel productoModel = (DefaultComboBoxModel) comboProducto.getModel();
        DefaultComboBoxModel postulanteModel = (DefaultComboBoxModel) comboPostulante.getModel();
        
        productoModel.removeAllElements();
        productoModel.addAll(Producto.obtenerTodos());
        
        postulanteModel.removeAllElements();
        postulanteModel.addAll(Postulante.obtenerTodos());
        
    }
